-- 7. 根据交易汇总更新账户余额（无触发器时的备用方案）
-- ============================================================
-- 通过子查询计算各账户实际余额并更新
UPDATE account a SET balance = (
    COALESCE(
        (
            SELECT
                SUM(CASE WHEN t.trans_type = '收入' THEN t.amount ELSE -t.amount END)
            FROM transaction_record t
            WHERE t.account_id = a.account_id
        ),
        0
    )
);

